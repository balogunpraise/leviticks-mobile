/// Corner radii mirrored from the Tailwind classes used on the web
/// (`rounded-md`, `rounded-lg`, `rounded-xl`, `rounded-2xl`) so cards, chips
/// and buttons read consistently between platforms.
class AppRadius {
  AppRadius._();

  static const double md = 6;
  static const double lg = 8;
  static const double xl = 12;
  static const double xl2 = 16;
  static const double full = 999;
}
